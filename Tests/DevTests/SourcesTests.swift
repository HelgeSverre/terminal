import Foundation
import Testing
@testable import dev

@Suite struct SourcesTests {
  @Test("sources: files are listed in order and generated ones recognised") func filesAreListedInOrder() throws {
    try withTemporaryDirectory("dev-sources-") { root in
      for directory in Sources.directories {
        try FileManager.default.createDirectory(atPath: root + "/" + directory + "/Inner", withIntermediateDirectories: true)
      }
      try "// Generated by a tool\n".write(toFile: root + "/Sources/Table.swift", atomically: true, encoding: .utf8)
      try "let a = 1\n".write(toFile: root + "/Sources/Inner/A.swift", atomically: true, encoding: .utf8)
      try "notes\n".write(toFile: root + "/tools/README.md", atomically: true, encoding: .utf8)
      #expect(try Sources.swiftFiles(root: root) == ["Sources/Inner/A.swift", "Sources/Table.swift"], "two Swift files, sorted")
      #expect(try Sources.isGenerated("Sources/Table.swift", root: root), "generated file recognised")
      #expect(try !Sources.isGenerated("Sources/Inner/A.swift", root: root), "hand-written file recognised")
    }
  }
}
