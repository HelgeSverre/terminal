// Generates Sources/Terminal/Text/TerminalWidthTables.swift from the exact generated tables
// extracted from pinned unicode-width 0.2.3 into tools/unicode. This is a data
// formatter, not a Unicode-property implementation: its output must preserve the
// crate's scalar decisions byte-for-byte. Invoke with:
// xcrun swiftc -parse-as-library tools/GenerateTerminalWidth.swift -o
// target/native/generate-terminal-width && target/native/generate-terminal-width
import CryptoKit
import Foundation

@main enum GenerateTerminalWidth {
  static func main() throws {
    let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
    let input = root.appendingPathComponent("tools/unicode/terminal-width-18.0.0.json")
    let output = root.appendingPathComponent("Sources/Terminal/Text/TerminalWidthTables.swift")
    let data = try Data(contentsOf: input)
    let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    guard digest == "5659728c03da5ff3d09aedf3ee6f54e797efc903650f7724cf76b2b43d9c7ec3" else {
      fatalError("width input checksum changed: \(digest)")
    }
    let tables = try JSONDecoder().decode(Tables.self, from: data)
    guard tables.unicodeVersion == "18.0.0", tables.unicodeWidthVersion == "0.2.3",
      tables.widthRoot.count == 256, tables.widthMiddle.count == 1024,
      tables.widthLeaves.count == 5280, tables.emojiPresentationLeaves.count == 896,
      tables.nonTransparentZeroWidths.count == 74,
      tables.textPresentationLeaves.count == 10, tables.emojiModifierLeaves.count == 8
    else { fatalError("incomplete pinned width tables") }
    let rootBytes = tables.widthRoot, middleBytes = tables.widthMiddle
    let leafBytes = tables.widthLeaves, emojiBytes = tables.emojiPresentationLeaves
    let nonTransparent = tables.nonTransparentZeroWidths.map { ($0[0], $0[1]) }
    let textLeaves = tables.textPresentationLeaves.map { $0.map { ($0[0], $0[1]) } }
    let modifierLeaves = tables.emojiModifierLeaves.map { $0.map { ($0[0], $0[1]) } }

    let generated = """
    // Generated by tools/GenerateTerminalWidth.swift from unicode-width 0.2.3
    // (Unicode 18.0.0), pinned in tools/unicode/terminal-width-18.0.0.json. Do not edit.
    // Derived data is Copyright 2012-2026 The Rust Project Developers and is
    // licensed Apache-2.0 OR MIT; see Resources/Terminal/THIRD_PARTY_NOTICES.md.
    enum TerminalWidthTables {
      static let unicodeVersion = "18.0.0"
      static let unicodeWidthVersion = "0.2.3"
      static let widthRoot: [UInt8] = [
    \(format(rootBytes))
      ]
      static let widthMiddle: [UInt8] = [
    \(format(middleBytes))
      ]
      static let widthLeaves: [UInt8] = [
    \(format(leafBytes))
      ]
      static let emojiPresentationLeaves: [UInt8] = [
    \(format(emojiBytes))
      ]
      static let nonTransparentZeroWidths: [(UInt32, UInt32)] = [
    \(format(nonTransparent))
      ]
      static let textPresentationLeaves: [[(UInt8, UInt8)]] = [
    \(textLeaves.map { format($0) }.joined(separator: ",\n"))
      ]
      static let emojiModifierLeaves: [[(UInt8, UInt8)]] = [
    \(modifierLeaves.map { format($0) }.joined(separator: ",\n"))
      ]

      static func contains(_ ranges: [(UInt8, UInt8)], _ value: UInt8) -> Bool {
        var low = 0, high = ranges.count
        while low < high {
          let middle = (low + high) / 2
          if ranges[middle].1 < value { low = middle + 1 } else { high = middle }
        }
        return ranges.indices.contains(low) && ranges[low].0 <= value
      }

      static func contains(_ ranges: [(UInt32, UInt32)], _ value: UInt32) -> Bool {
        var low = 0, high = ranges.count
        while low < high {
          let middle = (low + high) / 2
          if ranges[middle].1 < value { low = middle + 1 } else { high = middle }
        }
        return ranges.indices.contains(low) && ranges[low].0 <= value
      }
    }
    """
    try generated.write(to: output, atomically: true, encoding: .utf8)
    print("Generated Unicode 18 terminal width tables: root=\(rootBytes.count), middle=\(middleBytes.count), leaves=\(leafBytes.count)")
  }

  private struct Tables: Decodable {
    let unicodeVersion: String
    let unicodeWidthVersion: String
    let widthRoot: [UInt8]
    let widthMiddle: [UInt8]
    let widthLeaves: [UInt8]
    let emojiPresentationLeaves: [UInt8]
    let nonTransparentZeroWidths: [[UInt32]]
    let textPresentationLeaves: [[[UInt8]]]
    let emojiModifierLeaves: [[[UInt8]]]
  }

  private static func format(_ values: [UInt8]) -> String {
    stride(from: 0, to: values.count, by: 16).map { offset in "        " + values[offset..<min(offset + 16, values.count)].map { String(format: "0x%02X", $0) }.joined(separator: ", ") + "," }.joined(separator: "\n")
  }
  private static func format(_ values: [(UInt32, UInt32)]) -> String {
    values.map { "        (0x\(String($0.0, radix: 16)), 0x\(String($0.1, radix: 16)))," }.joined(separator: "\n")
  }
  private static func format(_ values: [(UInt8, UInt8)]) -> String {
    "        [" + values.map { "(0x\(String($0.0, radix: 16)), 0x\(String($0.1, radix: 16)))" }.joined(separator: ", ") + "]"
  }
}
