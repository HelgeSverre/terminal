// Generates native/TerminalWidthTables.swift from the exact generated tables
// in the pinned unicode-width 0.2.3 crate.  This is intentionally a source
// copier, not a Unicode-property implementation: its output must preserve the
// crate's scalar decisions byte-for-byte. Invoke with:
// xcrun swiftc -parse-as-library tools/GenerateTerminalWidth.swift -o
// target/native/generate-terminal-width && target/native/generate-terminal-width
import Foundation

@main enum GenerateTerminalWidth {
  static func main() throws {
    let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
    let input = URL(fileURLWithPath: CommandLine.arguments.dropFirst().first ?? "/Users/helge/.cargo/registry/src/index.crates.io-1949cf8c6b5b557f/unicode-width-0.2.3/src/gen/tables.rs")
    let output = root.appendingPathComponent("native/TerminalWidthTables.swift")
    let rust = try String(contentsOf: input, encoding: .utf8)
    guard rust.contains("UNICODE_VERSION: (u8, u8, u8) = (18, 0, 0)") else { fatalError("expected unicode-width Unicode 18 table source") }

    let rootBytes = try bytes(in: rust, after: "static WIDTH_ROOT:", alignment: "Align128", count: 256)
    let middleBytes = try bytes(in: rust, after: "static WIDTH_MIDDLE:", alignment: "Align64", count: 16 * 64)
    let leafBytes = try bytes(in: rust, after: "static WIDTH_LEAVES:", alignment: "Align32", count: 165 * 32)
    let emojiBytes = try bytes(in: rust, after: "static EMOJI_PRESENTATION_LEAVES:", alignment: "Align128", count: 7 * 128)
    let nonTransparent = try tripleRanges(in: rust, after: "static NON_TRANSPARENT_ZERO_WIDTHS:", expected: 74)
    let textLeaves = try (0..<10).map { try byteRanges(in: rust, after: "static TEXT_PRESENTATION_LEAF_\($0):") }
    let modifierLeaves = try (0..<8).map { try byteRanges(in: rust, after: "static EMOJI_MODIFIER_LEAF_\($0):") }

    let generated = """
    // Generated by tools/GenerateTerminalWidth.swift from unicode-width 0.2.3
    // (Unicode 18.0.0), locked in the local Cargo registry. Do not edit.
    // Derived data is Copyright 2012-2026 The Rust Project Developers and is
    // licensed Apache-2.0 OR MIT; see native/THIRD_PARTY_NOTICES.md.
    enum TerminalWidthTables {
      static let unicodeVersion = "18.0.0"
      static let unicodeWidthVersion = "0.2.3"
      static let widthRoot: [UInt8] = [
    \(format(rootBytes))
      ]
      static let widthMiddle: [UInt8] = [
    \(format(middleBytes))
      ]
      static let widthLeaves: [UInt8] = [
    \(format(leafBytes))
      ]
      static let emojiPresentationLeaves: [UInt8] = [
    \(format(emojiBytes))
      ]
      static let nonTransparentZeroWidths: [(UInt32, UInt32)] = [
    \(format(nonTransparent))
      ]
      static let textPresentationLeaves: [[(UInt8, UInt8)]] = [
    \(textLeaves.map { format($0) }.joined(separator: ",\n"))
      ]
      static let emojiModifierLeaves: [[(UInt8, UInt8)]] = [
    \(modifierLeaves.map { format($0) }.joined(separator: ",\n"))
      ]

      static func contains(_ ranges: [(UInt8, UInt8)], _ value: UInt8) -> Bool {
        var low = 0, high = ranges.count
        while low < high {
          let middle = (low + high) / 2
          if ranges[middle].1 < value { low = middle + 1 } else { high = middle }
        }
        return ranges.indices.contains(low) && ranges[low].0 <= value
      }

      static func contains(_ ranges: [(UInt32, UInt32)], _ value: UInt32) -> Bool {
        var low = 0, high = ranges.count
        while low < high {
          let middle = (low + high) / 2
          if ranges[middle].1 < value { low = middle + 1 } else { high = middle }
        }
        return ranges.indices.contains(low) && ranges[low].0 <= value
      }
    }
    """
    try generated.write(to: output, atomically: true, encoding: .utf8)
    print("Generated Unicode 18 terminal width tables: root=\(rootBytes.count), middle=\(middleBytes.count), leaves=\(leafBytes.count)")
  }

  private static func bytes(in source: String, after marker: String, alignment: String, count: Int) throws -> [UInt8] {
    let body = try bracketBody(in: source, after: marker, openingAfter: " = \(alignment)([")
    let regex = try NSRegularExpression(pattern: #"0x([0-9A-Fa-f]{2})"#)
    let ns = body as NSString
    let values = regex.matches(in: body, range: NSRange(location: 0, length: ns.length)).compactMap { UInt8(ns.substring(with: $0.range(at: 1)), radix: 16) }
    guard values.count >= count else { throw ParseError("\(marker): expected at least \(count) bytes, found \(values.count)") }
    return Array(values.prefix(count))
  }

  private static func tripleRanges(in source: String, after marker: String, expected: Int) throws -> [(UInt32, UInt32)] {
    let body = try bracketBody(in: source, after: marker, openingAfter: " = [")
    let regex = try NSRegularExpression(pattern: #"\(\[0x([0-9A-Fa-f]{2}), 0x([0-9A-Fa-f]{2}), 0x([0-9A-Fa-f]{2})\], \[0x([0-9A-Fa-f]{2}), 0x([0-9A-Fa-f]{2}), 0x([0-9A-Fa-f]{2})\]\)"#)
    let ns = body as NSString
    let values = regex.matches(in: body, range: NSRange(location: 0, length: ns.length)).map { match -> (UInt32, UInt32) in
      let numbers = (1...6).map { UInt32(ns.substring(with: match.range(at: $0)), radix: 16)! }
      // unicode-width stores these compact three-byte code points in
      // little-endian order and reconstructs them with `from_le_bytes`.
      return (numbers[0] | (numbers[1] << 8) | (numbers[2] << 16), numbers[3] | (numbers[4] << 8) | (numbers[5] << 16))
    }
    guard values.count == expected else { throw ParseError("\(marker): expected \(expected) ranges, found \(values.count)") }
    return values
  }

  private static func byteRanges(in source: String, after marker: String) throws -> [(UInt8, UInt8)] {
    let body = try bracketBody(in: source, after: marker, openingAfter: " = [")
    let regex = try NSRegularExpression(pattern: #"\(0x([0-9A-Fa-f]{2}), 0x([0-9A-Fa-f]{2})\)"#)
    let ns = body as NSString
    let values = regex.matches(in: body, range: NSRange(location: 0, length: ns.length)).map { (UInt8(ns.substring(with: $0.range(at: 1)), radix: 16)!, UInt8(ns.substring(with: $0.range(at: 2)), radix: 16)!) }
    guard !values.isEmpty else { throw ParseError("\(marker): no ranges") }
    return values
  }

  private static func bracketBody(in source: String, after marker: String, openingAfter opener: String) throws -> String {
    guard let markerRange = source.range(of: marker), let openingRange = source.range(of: opener, range: markerRange.upperBound..<source.endIndex), let start = source[openingRange].firstIndex(of: "[") else { throw ParseError("missing \(marker)") }
    var depth = 0
    for index in source[start...].indices {
      if source[index] == "[" { depth += 1 }
      if source[index] == "]" {
        depth -= 1
        if depth == 0 { return String(source[source.index(after: start)..<index]) }
      }
    }
    throw ParseError("unterminated \(marker)")
  }

  private static func format(_ values: [UInt8]) -> String {
    stride(from: 0, to: values.count, by: 16).map { offset in "        " + values[offset..<min(offset + 16, values.count)].map { String(format: "0x%02X", $0) }.joined(separator: ", ") + "," }.joined(separator: "\n")
  }
  private static func format(_ values: [(UInt32, UInt32)]) -> String {
    values.map { "        (0x\(String($0.0, radix: 16)), 0x\(String($0.1, radix: 16)))," }.joined(separator: "\n")
  }
  private static func format(_ values: [(UInt8, UInt8)]) -> String {
    "        [" + values.map { "(0x\(String($0.0, radix: 16)), 0x\(String($0.1, radix: 16)))" }.joined(separator: ", ") + "]"
  }
  private struct ParseError: Error, CustomStringConvertible { let message: String; init(_ message: String) { self.message = message }; var description: String { message } }
}
