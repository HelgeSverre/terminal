#!/usr/bin/env ruby
# frozen_string_literal: true

require 'json'
require 'fileutils'
require_relative 'native_smoke'

# Launches a single owned app with a fixed raw-PTY child. The child neither
# reads shell startup files nor persists any terminal or clipboard contents.
class SelectionSmoke
  CHECKS = %w[
    fixture_ready wide_drag ordinary_forward_copy ordinary_reverse_copy word_double_click private_copy output_preserves_selection
    reflow_retains_selection line_triple_click rectangular_option_drag rectangular_ax_multirange_has_no_union_holes
    plain_click_publishes_caret_without_selection
    application_mouse_does_not_select original_pane_close_cancels_pending
    private_board_unchanged_after_close completed_without_timeout
  ].freeze
  EXPECTED_TEXT = %w[WORD_TOKEN 猫 SEL_WIDE_猫_TOKEN LINE_TOKEN abcde ABCDE CLICK_TAIL CLOSE_TOKEN].freeze

  def initialize(root, bundle)
    @root = root
    @bundle = bundle
    @app = File.join(bundle, 'Contents', 'MacOS', 'Terminal')
    @output = ENV.fetch('TERMINAL_SELECTION_SMOKE_REPORT_DIRECTORY', File.join(root, 'reports'))
    @path = File.join(@output, 'selection-smoke.json')
  end

  def run
    abort "Missing executable: #{@app}" unless File.executable?(@app)
    FileUtils.mkdir_p(@output)
    File.delete(@path) if File.exist?(@path)
    report = nil
    process = NativeSmokeProcess.new([
      @app, '--selection-smoke', @path, '--columns', '48', '--rows', '14', '--font-size', '14',
      '--working-directory', '/tmp', '--execute', '/bin/sh', '-c', fixture,
      out: File::NULL, err: File::NULL
    ])
    begin
      status = process.wait(45)
      raise 'Selection smoke timed out' unless status
      raise "Selection smoke exited with #{status}" unless status.success?
      raise "Selection smoke left children: #{process.live_pids.join(', ')}" unless process.live_pids.empty?

      report = JSON.parse(File.read(@path))
      checks = report.fetch('checks')
      missing = CHECKS.reject { |check| checks.fetch(check, false) }
      raise "Selection checks failed: #{missing.join(', ')}" unless missing.empty?
      counts = report.fetch('counts')
      raise 'Selection smoke reported inconsistent check counts' unless counts.fetch('required_checks') == CHECKS.length && counts.fetch('passed_checks') == CHECKS.length
      raise 'Selection smoke omitted its fixed expected text' unless report.fetch('expected_known_text') == EXPECTED_TEXT
      raise 'Selection smoke did not mark report passed' unless report.fetch('passed')
      report['runner'] = { 'app_exited' => true, 'cleanup_survivors' => [] }
    rescue Exception => error # Preserve a compact failure report before re-raising.
      report ||= {}
      report['passed'] = false
      report['runner_error'] = error.message
      raise
    ensure
      begin
        remaining = process.cleanup
        report ||= {}
        report['runner'] ||= {}
        report['runner']['cleanup_survivors'] = remaining
        raise "Selection smoke cleanup survivors: #{remaining.join(', ')}" unless remaining.empty?
      rescue Exception => error
        report ||= {}
        report['passed'] = false
        report['cleanup_error'] = error.message
        raise
      ensure
        File.write(@path, JSON.pretty_generate(report) + "\n") if report
      end
    end
    puts 'PASS selection smoke: owned AppKit gestures, private copy, reflow, mouse routing and close cleanup'
  end

  private

  def fixture
    # OUTPUT and MOUSE are exact raw control messages from the owned smoke. The
    # resulting output is always generated by this child, never user content.
    [
      'stty raw -echo',
      'dd bs=1 count=1 of=/dev/null 2>/dev/null',
      "printf 'SELECTION_FIXTURE_READY SEL_WIDE_猫_TOKEN\\r\\n'",
      'dd bs=1 count=5 of=/dev/null 2>/dev/null',
      "printf 'WORD_TOKEN\\r\\n'",
      'dd bs=1 count=7 of=/dev/null 2>/dev/null',
      "printf 'SELECTION_OUTPUT_AFTER_GESTURE\\r\\n'",
      'dd bs=1 count=5 of=/dev/null 2>/dev/null',
      "printf 'LINE_TOKEN\\r\\n'",
      'dd bs=1 count=5 of=/dev/null 2>/dev/null',
      "printf 'abcde\\r\\nABCDE\\r\\n'",
      'dd bs=1 count=5 of=/dev/null 2>/dev/null',
      "printf 'CLICK_TAIL\\r\\n'",
      'dd bs=1 count=6 of=/dev/null 2>/dev/null',
      "printf '\\033[?1000hMOUSE_MODE_READY\\r\\n'",
      'dd bs=1 count=6 of=/dev/null 2>/dev/null',
      "printf 'MOUSE_ROUTE_ACK\\r\\nCLOSE_TOKEN\\r\\n\\033[?1000lMOUSE_DISABLED\\r\\n'",
      'exec /bin/sleep 30',
    ].join('; ')
  end
end

if $PROGRAM_NAME == __FILE__
  Signal.trap('TERM') { raise Interrupt, 'Selection smoke interrupted' }
  Signal.trap('INT') { raise Interrupt, 'Selection smoke interrupted' }
  abort 'Usage: ruby tools/selection_smoke.rb [app-bundle]' if ARGV.length > 1

  root = File.expand_path('..', __dir__)
  bundle = File.expand_path(ARGV.fetch(0, 'dist/Terminal.app'), root)
  SelectionSmoke.new(root, bundle).run
end
